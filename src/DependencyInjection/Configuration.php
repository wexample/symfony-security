<?php

namespace Wexample\SymfonySecurity\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('wexample_symfony_security');

        $treeBuilder->getRootNode()
            ->children()
                ->arrayNode('redaction')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('query_parameters')
                            ->info('Query parameters whose value is masked in every log record, as in "/link?token=[redacted]".')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                        ->arrayNode('patterns')
                            ->info('Regular expressions whose matches are masked in every log record. Keep what must stay readable in a lookaround: "/(?<=Bearer )\S+/".')
                            ->scalarPrototype()
                                ->validate()
                                    ->ifTrue(static fn (string $pattern) => false === @preg_match($pattern, ''))
                                    ->thenInvalid('%s is not a valid regular expression.')
                                ->end()
                            ->end()
                            ->defaultValue([])
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('rate_limits')
                    ->info('Limits the application declares on whole groups of requests, beside the #[RateLimit] of a controller: '
                        .'every write, the forms that send a mail, the endpoints that cost. Each counts on its own, per address or per user, '
                        .'over a sliding window; beyond it the request is answered 429, as for the attribute.')
                    ->arrayPrototype()
                        ->children()
                            ->scalarNode('name')
                                ->info('The count, shared by every request the rule matches.')
                                ->isRequired()
                                ->cannotBeEmpty()
                            ->end()
                            ->integerNode('limit')
                                ->isRequired()
                                ->min(1)
                            ->end()
                            ->scalarNode('interval')
                                ->info('As the rate limiter reads it: "1 minute", "15 minutes", "1 hour".')
                                ->isRequired()
                                ->cannotBeEmpty()
                            ->end()
                            ->enumNode('scope')
                                ->values(['ip', 'user'])
                                ->defaultValue('ip')
                            ->end()
                            ->arrayNode('methods')
                                ->info('The methods counted; every one when empty.')
                                ->scalarPrototype()
                                    ->beforeNormalization()->always(static fn ($method) => strtoupper((string) $method))->end()
                                ->end()
                                ->defaultValue([])
                            ->end()
                            ->scalarNode('routes')
                                ->info('A regular expression the route name must match: "/^api_invoice_(emit|peppol_send)$/".')
                                ->defaultNull()
                                ->validate()
                                    ->ifTrue(static fn (?string $pattern) => null !== $pattern && false === @preg_match($pattern, ''))
                                    ->thenInvalid('%s is not a valid regular expression.')
                                ->end()
                            ->end()
                            ->scalarNode('paths')
                                ->info('A regular expression the path must match, for what one route serves under many names: "#^/_forms/submit/form-password_reset_request_form$#".')
                                ->defaultNull()
                                ->validate()
                                    ->ifTrue(static fn (?string $pattern) => null !== $pattern && false === @preg_match($pattern, ''))
                                    ->thenInvalid('%s is not a valid regular expression.')
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                    ->defaultValue([])
                ->end()
                ->arrayNode('proof_of_work')
                    ->info('The captcha a form carries with ProofOfWorkService: work the browser does before sending, checked by the server in one hash.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('max_number')
                            ->info('The highest number the browser may have to try: half of it on average, a few hundred milliseconds at the default.')
                            ->defaultValue(100000)
                            ->min(1)
                        ->end()
                        ->integerNode('lifetime')
                            ->info('Seconds a challenge stays valid once issued: the time to fill the form in.')
                            ->defaultValue(3600)
                            ->min(1)
                        ->end()
                        ->integerNode('min_delay')
                            ->info('Seconds before a challenge may be sent back: a form filled in faster was filled in by a program.')
                            ->defaultValue(3)
                            ->min(0)
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('headers')
                    ->info('Security headers added to every main response that does not set them already; null leaves one out.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('strict_transport_security')
                            ->info('Sent over HTTPS only. Once a browser has read it, it refuses plain HTTP on the host for max-age seconds.')
                            ->defaultValue('max-age=31536000; includeSubDomains')
                        ->end()
                        ->scalarNode('content_type_options')
                            ->defaultValue('nosniff')
                        ->end()
                        ->scalarNode('frame_options')
                            ->info('Who may show the pages in a frame. DENY when no page of the application is ever framed.')
                            ->defaultValue('SAMEORIGIN')
                        ->end()
                        ->scalarNode('referrer_policy')
                            ->defaultValue('strict-origin-when-cross-origin')
                        ->end()
                        ->scalarNode('content_security_policy')
                            ->info('Off by default: a policy is written against the scripts and styles of the application, not guessed.')
                            ->defaultNull()
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
